function sendAccessRequest() {
    const input = document.getElementById('doctorGrantInput');
    const docName = input ? input.value.trim() : '';
    if (!docName) return;

    const msg = document.getElementById('grantStatusMsg');
    if (msg) {
        msg.classList.remove('hidden');
        msg.textContent = `✓ Access permission issued to ${docName}`;
    }
    const docList = document.getElementById('authorizedDoctorsList');
    if (docList) {
        docList.innerHTML = `<span class="bg-amber-100 text-amber-800 px-2.5 py-1 rounded-md font-semibold text-[11px]">${docName} (Pending Authorization)</span>`;
    }
}

function acceptAccessRequest() {
    isAccessGranted = true;
    const banner = document.getElementById('doctorAccessRequestBanner');
    if (banner) banner.classList.add('hidden');

    const badge = document.getElementById('accessStatusBadge');
    if (badge) {
        badge.className = "bg-emerald-100 text-emerald-800 font-bold text-xs px-3 py-1 rounded-full";
        badge.textContent = "Access: Active & Verified";
    }
    renderDocumentLists();
}

