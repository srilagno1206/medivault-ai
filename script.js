function quickSymptom(text) {
    const input = document.getElementById('chatInput');
    if (input) {
        input.value = text;
        handleChatSubmit(new Event('submit'));
    }
}

function handleChatSubmit(e) {
    e.preventDefault();
    const input = document.getElementById('chatInput');
    const text = input ? input.value.trim() : '';
    if (!text) return;

    const chatContainer = document.getElementById('chatContainer');
    chatContainer.insertAdjacentHTML('beforeend', `
        <div class="flex justify-end">
            <div class="max-w-[80%] rounded-2xl p-4 text-xs leading-relaxed bg-emerald-600 text-white rounded-br-none">
                ${text}
            </div>
        </div>
    `);
    if (input) input.value = '';
    chatContainer.scrollTop = chatContainer.scrollHeight;

    const emergencyKeywords = ['chest pain', 'heart attack', 'cannot breathe', 'fainting', 'unconscious', 'severe bleeding', 'stroke'];
    const isEmergency = emergencyKeywords.some(kw => text.toLowerCase().includes(kw));

    setTimeout(() => {
        if (isEmergency) {
            const alertBanner = document.getElementById('emergencyAlertBanner');
            if (alertBanner) alertBanner.classList.remove('hidden');

            chatContainer.insertAdjacentHTML('beforeend', `
                <div class="flex justify-start">
                    <div class="max-w-[80%] rounded-2xl p-4 text-xs leading-relaxed bg-red-50 border border-red-200 text-red-800 shadow-sm rounded-bl-none font-semibold">
                        🚨 URGENT EMERGENCY ESCALATION: High-risk distress symptoms detected. Dr. Alok Sharma has been notified via priority SOS notification.
                    </div>
                </div>
            `);
        } else {
            chatContainer.insertAdjacentHTML('beforeend', `
                <div class="flex justify-start">
                    <div class="max-w-[80%] rounded-2xl p-4 text-xs leading-relaxed bg-white text-slate-800 border border-slate-100 shadow-sm rounded-bl-none">
                        Verified record context: Active prescription for Metformin 500mg daily. Latest HbA1c lab result: 6.8%.
                    </div>
                </div>
            `);
        }
        chatContainer.scrollTop = chatContainer.scrollHeight;
    }, 500);
}