function changeLanguage(langKey) {
    const dictionary = i18n[langKey] || i18n.en;
    document.querySelectorAll('[data-lang]').forEach(el => {
        const key = el.getAttribute('data-lang');
        if (dictionary[key]) {
            el.textContent = dictionary[key];
        }
    });
}

function attemptDoctorAccess() {
    if (isAuthenticatedDoctor) {
        switchTab('doctor');
    } else {
        setLoginRole('doctor');
        showLogin();
    }
}

function closeLoginModal() {
    document.getElementById('view-login').classList.add('hidden');
}

function showLogin() {
    document.getElementById('view-login').classList.remove('hidden');
}

function switchTab(tabId) {
    if (tabId === 'doctor' && !isAuthenticatedDoctor) {
        attemptDoctorAccess();
        return;
    }

    const tabs = ['home', 'services', 'assessment', 'locker', 'chatbot', 'doctor'];
    tabs.forEach(tab => {
        const el = document.getElementById(`view-${tab}`);
        if (el) el.classList.add('hidden');
    });

    const targetView = document.getElementById(`view-${tabId}`);
    if (targetView) targetView.classList.remove('hidden');
    window.scrollTo({ top: 0, behavior: 'smooth' });
}

function setLoginRole(role) {
    currentRole = role;
    const patientBtn = document.getElementById('roleBtnPatient');
    const doctorBtn = document.getElementById('roleBtnDoctor');
    const doctorField = document.getElementById('doctorIdFieldGroup');
    const title = document.getElementById('loginHeaderTitle');
    const sub = document.getElementById('loginSubText');

    if (role === 'doctor') {
        doctorBtn.className = "flex-1 py-2 text-xs font-bold rounded-xl bg-white text-emerald-700 shadow-sm transition-all flex items-center justify-center space-x-1.5";
        patientBtn.className = "flex-1 py-2 text-xs font-bold rounded-xl text-slate-500 hover:text-slate-800 transition-all flex items-center justify-center space-x-1.5";
        doctorField.classList.remove('hidden');
        title.textContent = "Doctor Workspace Login";
        sub.textContent = "Enter your physician license ID to open protected patient records.";
    } else {
        patientBtn.className = "flex-1 py-2 text-xs font-bold rounded-xl bg-white text-emerald-700 shadow-sm transition-all flex items-center justify-center space-x-1.5";
        doctorBtn.className = "flex-1 py-2 text-xs font-bold rounded-xl text-slate-500 hover:text-slate-800 transition-all flex items-center justify-center space-x-1.5";
        doctorField.classList.add('hidden');
        title.textContent = "Patient Workspace Login";
        sub.textContent = "Access encrypted records, consent sharing, and daily AI check-ins.";
    }
}

